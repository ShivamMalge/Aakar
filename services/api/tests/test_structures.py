# ------------------------------------------------ the two measured alternatives (D-067)


def test_the_refined_guard_keeps_the_distinguishing_token_and_still_drops_the_category() -> None:
    """The first live run: the approved guard rejected `photoreceptor` for "Photoreceptor
    cell" because it is a token of its own name. Refined, only a CATEGORY token falls."""
    cats = frozenset({"cell", "body"})
    assert synonym_rejection("Photoreceptor cell", "photoreceptor", [], category_nouns=cats) is None
    assert synonym_rejection("ciliary body", "body", [], category_nouns=cats)
    # The approved guard, unchanged, still rejects both — the refinement is opt-in.
    assert synonym_rejection("Photoreceptor cell", "photoreceptor", [])


def test_the_head_noun_rule_is_name_choice_sensitive() -> None:
    """What the live run actually showed: even refined, `photoreceptor` falls to the OTHER
    rule once the model has named rods "Rod photoreceptor". The guard's outcome depends
    on which canonical name the model chose — a finding, recorded, not resolved here."""
    cats = frozenset({"cell"})
    reason = synonym_rejection(
        "Photoreceptor cell", "photoreceptor", ["Rod photoreceptor"], category_nouns=cats
    )
    assert reason and "head noun of another entity" in reason


def test_singular_recovery_is_corpus_checked() -> None:
    """`rods` (copied from c07) -> `rod` only because the chapter also says "rod
    photoreceptor"; `lens` -> `len` is proposed and never admitted because nothing in the
    chapter is a "len". Both halves are the corpus check doing its job."""
    assert "rod" in singular_candidates("rods")
    assert singular_candidates("lens") == ("len",)
    proposal = _proposal(
        name="Rod photoreceptor",
        kind="cell_type",
        naming_chunk_ids=["c07", "c09"],
        surface_forms_in_text=["rods"],
        modellable=False,
    )
    without = decide([proposal], CHAPTER, category_nouns=CATEGORY)
    with_ = decide([proposal], CHAPTER, category_nouns=CATEGORY, recover_singulars=True)
    assert "rod" not in {normalise(f) for f in without.entities[0].all_forms}
    assert "rod" in {normalise(f) for f in with_.entities[0].all_forms}

    lens = _proposal(
        name="crystalline lens", naming_chunk_ids=["c01"], surface_forms_in_text=["lens"]
    )
    chapter = {**CHAPTER, "c02": ("541", "the lens focuses light")}
    got = decide([lens], chapter, category_nouns=CATEGORY, recover_singulars=True)
    assert "len" not in {normalise(f) for f in got.entities[0].all_forms}
