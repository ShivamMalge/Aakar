# ------------------------------------------------------------------ scoring


def test_the_label_set_fed_back_as_an_extraction_scores_perfectly() -> None:
    """Guards the guard: a scorer that cannot recognise the ground truth is broken."""
    labels = load_labels()
    proposals = [
        {
            "name": lab.name,
            "kind": lab.kind,
            "naming_chunk_ids": list(lab.naming_chunks),
            "surface_forms_in_text": list(lab.surface_forms),
            "synonyms": [],
            "abbreviations": ["RGC"] if lab.name == "retinal ganglion cell" else [],
            "modellable": lab.modellable,
        }
        for lab in labels.entities
    ]
    from aakar.evals.golden import load_golden_set

    golden = load_golden_set()
    chunks = {c.chunk_id: (c.page_label, c.text) for c in golden.chunks}
    extraction = decide(proposals, chunks, category_nouns=labels.rules.category_nouns)
    scores = score(extraction, labels)
    assert scores.counts(modellable_only=False) == (28, 0, 0)
    assert scores.counts(modellable_only=True) == (18, 0, 0)
    assert all(not c.uncovered for c in alias_coverage(scores))


def test_scoring_sees_a_miss_a_duplicate_and_an_invention() -> None:
    labels = load_labels()
    from aakar.evals.golden import load_golden_set

    golden = load_golden_set()
    chunks = {c.chunk_id: (c.page_label, c.text) for c in golden.chunks}
    proposals = [
        _proposal(name="eye", naming_chunk_ids=["c01"], surface_forms_in_text=["eye"]),
        _proposal(name="eyeball", naming_chunk_ids=["c03"], surface_forms_in_text=["eyeball"]),
        _proposal(name="cornea", naming_chunk_ids=["c01"], surface_forms_in_text=["cornea"]),
    ]
    scores = score(decide(proposals, chunks, category_nouns=labels.rules.category_nouns), labels)
    tp, fp, fn = scores.counts(modellable_only=False)
    assert (tp, fp) == (2, 1), "eyeball is a duplicate of eye, not a new structure"
    assert fn == 26
    assert any("duplicate" in why for _, why in scores.false_positives)


